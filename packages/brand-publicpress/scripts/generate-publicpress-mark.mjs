#!/usr/bin/env node
// Regenerates src/components/publicPressMark.generated.ts from
// scripts/publicpress-mark-spec.json, the mark's settled design spec (glyph
// outlines, block geometry, inks). This script only transcribes it into a
// typed module so the path data is never retyped by hand.
//
// Usage: node scripts/generate-publicpress-mark.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const specPath = path.join(here, 'publicpress-mark-spec.json');
const outPath = path.join(here, '..', 'src', 'components', 'publicPressMark.generated.ts');

const spec = JSON.parse(readFileSync(specPath, 'utf8'));

function json(value) {
  return JSON.stringify(value);
}

const glyphNames = Object.keys(spec.glyphs);

const glyphEntries = glyphNames
  .map((name) => {
    const glyph = spec.glyphs[name];
    return `  ${json(name)}: { d: ${json(glyph.d)}, adv: ${json(glyph.adv)} },`;
  })
  .join('\n');

const inkNames = Object.keys(spec.inks);
const inkEntries = inkNames
  .map((name) => {
    const ink = spec.inks[name];
    return `  ${json(name)}: { block: ${json(ink.block)}, letters: ${json(ink.letters)} },`;
  })
  .join('\n');

const kerning = spec.kerning ?? {};
const kerningEntries = Object.keys(kerning)
  .map((pair) => `  ${json(pair)}: ${json(kerning[pair])},`)
  .join('\n');

const output = `// Generated by scripts/generate-publicpress-mark.mjs from
// scripts/publicpress-mark-spec.json. Do not edit by hand — regenerate
// instead. Glyph outlines are Libre Franklin Bold (SIL OFL 1.1); pilcrowP is
// the final PublicPress mark.
//
// Font units, 1000 per em, y up, baseline at y=0.

export interface PublicPressGlyph {
  readonly d: string;
  readonly adv: number;
}

export const UNITS_PER_EM = ${json(spec.unitsPerEm)};
export const CAP_HEIGHT = ${json(spec.capHeight)};

export const PUBLIC_PRESS_BLOCK = {
  top: ${json(spec.block.top)},
  bottom: ${json(spec.block.bottom)},
  sides: ${json(spec.block.sides)},
  gapAfterC: ${json(spec.block.gapAfterC)},
  height: ${json(spec.block.height)},
} as const;

export const PUBLIC_PRESS_GLYPHS: Readonly<Record<string, PublicPressGlyph>> = {
${glyphEntries}
};

export const PUBLIC_PRESS_WORDMARK_SEQUENCE: readonly string[] = ${json(spec.sequence)};

// Keyed \`"<left> <right>"\` by glyph name, applied between consecutive
// letters when laying the sequence out (see publicPressGeometry.ts). A
// negative value pulls the right glyph closer; glyphs with no entry here use
// their own advance unchanged. Never applied across a GAP.
export const PUBLIC_PRESS_KERNING: Readonly<Record<string, number>> = {
${kerningEntries}
};

export type PublicPressColor = ${inkNames.map((name) => json(name)).join(' | ')};

export const PUBLIC_PRESS_INKS: Readonly<Record<PublicPressColor, { block: string; letters: string }>> = {
${inkEntries}
};
`;

writeFileSync(outPath, output);
// eslint-disable-next-line no-console
console.log(`Wrote ${path.relative(process.cwd(), outPath)}`);
